-- DATA_NOTES A-3: trdar.prj의 Central Meridian 127, False Northing 500000은 EPSG:5181.
-- PostGIS 16-3.5 spatial_ref_sys에 기본 포함되는 EPSG:5181을 사용한다.
CREATE TABLE service_industries (
    service_code varchar(10) PRIMARY KEY,
    name text NOT NULL,
    category varchar(10) NOT NULL CHECK (category IN ('FOOD','SERVICE','RETAIL')),
    has_sales boolean NOT NULL DEFAULT false
);
CREATE TABLE trade_areas (
    area_code varchar(20) PRIMARY KEY,
    name text NOT NULL,
    area_type_code varchar(10), area_type_name text,
    district_code varchar(10), district_name text,
    dong_code varchar(10), dong_name text,
    area_m2 numeric,
    geom geometry(MultiPolygon,4326) NOT NULL,
    centroid geometry(Point,4326) NOT NULL,
    version_id bigint REFERENCES data_versions(id)
);
CREATE INDEX trade_areas_geom ON trade_areas USING gist(geom);
CREATE INDEX trade_areas_centroid ON trade_areas USING gist(centroid);
CREATE INDEX trade_areas_district ON trade_areas(district_code);

